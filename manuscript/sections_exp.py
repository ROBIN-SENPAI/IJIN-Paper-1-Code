def _pct(x):
    return f"{100 * x:.1f}%"


def _design_selection(m):
    """Validation-only choice of the trust-score form (design_val.py); numbers from design_val_summary.json."""
    with open(DESIGN_VAL) as f:
        V = json.load(f)
    adopt, add, orig, both = (V[k] for k in ("V2_veto_notwinrisk", "V3_additive_notwinrisk", "V0_additive_twinrisk",
                                             "V1_veto_twinrisk"))
    allv = (adopt, add, orig, both)
    best = (adopt["worm"] >= max(v["worm"] for v in allv)
            and all(adopt[k] <= min(v[k] for v in allv) for k in ("evasion", "injection")))
    small = max(abs(adopt[k] - add[k]) for k in ("worm", "evasion", "injection")) < 0.02
    tri = lambda v: f"{v['worm']:.4f}, {_pct(v['evasion'])} and {_pct(v['injection'])}"   # CE as a fraction, as in Tables 9 and 11
    if best:
        verdict = ("We adopted the first variant, Eq. {eq:trust}, which was best on all three measures"
                   + (", although its margin over the second was small. " if small else ". "))
    else:
        verdict = "We adopted the first variant, Eq. {eq:trust}. "
    m.para("The form of the trust score was fixed on validation episodes only. Four variants, the score with or "
           "without the zero-trust veto and with or without the twin's propagation risk $D_{i}$ of Eq. {eq:twinrisk}, "
           "were calibrated under the same budget and run on validation attack episodes (seeds 101–108, validation "
           "evidence pool). Worm containment efficiency and the attack-success ratios of credential misuse and data "
           f"injection were {tri(adopt)} with the veto and without $D_{{i}}$; {tri(add)} for the additive score "
           f"without $D_{{i}}$; {tri(orig)} for the original design (additive, with $D_{{i}}$); and {tri(both)} with "
           "the veto and $D_{i}$. " + verdict +
           "The second and third are kept as ablations of the veto alone and of both changes together. The comparison "
           "was prompted by earlier development runs on seeds 1–20, which drew on the test evidence pool and showed "
           "that the original design contained the worm more slowly than FL-only IDS. All reported city-scale "
           "results use 20 fresh test seeds (21–40) that were run only after the design and every $\\theta$ had been "
           "fixed; no seed in that range was used to select the design or to calibrate $\\theta$.")


def experimental_design(m, S):
    D = S["data"]
    m.heading("4. Experimental Design and Evaluation Protocol", 1)
    m.para("The evaluation addresses five questions: (i) whether trust-aware aggregation keeps the federated detector "
           "accurate on heterogeneous data and under poisoning; (ii) whether the full orchestration loop contains "
           "attacks better than simpler policies when every policy is held to the same false-blocking and "
           "service-disruption budget; (iii) what each component contributes; (iv) what post-quantum handshakes "
           "cost and how much exposure they remove; and (v) how A-PQZTO behaves with an imperfect twin, a faster worm "
           "and a larger city. Every number in Section 5 was generated by the code released with this paper.")

    m.heading("4.1 Datasets, preprocessing and leakage audit", 2)
    m.label_next("tab", "data")
    t, e, c = D["ton"], D["edge"], D["cic"]
    m.para("We used three public datasets and processed each one separately, because their schemas and label sets are "
           "incompatible [@moustafa2021toniot; @ferrag2022edgeiiot; @neto2023ciciot]. For TON_IoT, we used the network "
           f"train/test file ({t['rows_raw']:,} records). The copy we obtained contains all attack records of the "
           "official release (20,000 per attack type and 1,043 man-in-the-middle records) but 50,000 normal records "
           "instead of 300,000, so its benign class is smaller than in the release described by the dataset authors. "
           f"For Edge-IIoTset, we used the machine-learning subset ({e['rows_raw']:,} records, 63 columns). For "
           f"CICIoT2023, we used the first two merged CSV files ({c['rows_raw']:,} flows) and grouped their 34 labels "
           "into the eight families defined by the dataset authors: benign, DDoS, DoS, Mirai, reconnaissance, "
           "spoofing, web and brute force. File hashes are listed in the data availability statement.")
    m.para("We applied the same preprocessing steps to every dataset. Host and session identifiers (IP addresses, "
           "source ports, DNS queries, URIs, user agents, TLS subjects and issuers, frame times, raw TCP sequence and "
           "acknowledgement numbers, checksums, payloads and MQTT messages) were removed. Placeholder values were "
           "normalised so that '0', '0.0' and '-' denote the same missing value. Edge-IIoTset spells the placeholder "
           "differently in its normal and attack captures, so without this step the spelling alone would reveal the "
           "label [@galal2026provenance]. Exact duplicates were discarded, together with every record whose feature "
           "vector also occurs under a different label, because no detector can separate such records. Each dataset "
           "was then split 70/15/15 into stratified training, validation and test sets, with a different random split "
           "for every seed. Categorical fields were one-hot encoded over their 30 most frequent training values, and "
           "numerical fields were log-transformed and standardised; all encoders and scalers were fitted on the "
           "training split only. For CICIoT2023, each family was capped at 40,000 flows after deduplication to keep "
           "its training time comparable to that of TON_IoT.")
    m.para("Before training any model, we ran a single-feature leakage audit: for every column, we computed the best "
           "accuracy with which a one-feature rule (the majority label per value, or a single threshold) separates "
           "attack from benign traffic. An accuracy close to one indicates a shortcut that a detector could learn in "
           "place of traffic behaviour [@arp2022dosdonts]. Table {tab:data} reports the outcome of each step and of "
           "the audit.")
    rows = []
    for k in ("ton", "edge", "cic"):
        d = D[k]
        a = d["leakage_audit"]
        top = a["top_single_feature"][0]
        rows.append([DS_NAME[k], f"{d['rows_raw']:,}", f"{d['rows_after_dedup']:,}", f"{d['label_conflicts_removed']:,}",
                     f"{d['rows_used']:,}", str(d["n_features"]), str(len(d["classes"])),
                     f"{d['class_counts'][d['classes'][0]]:,}", f"{100 * a['majority_baseline']:.1f}",
                     f"{100 * a['max']:.1f} ({top[0]})"])
    m.table(["Dataset", "Raw rows", "Unique rows", "Label-conflicting rows removed", "Rows used", "Features",
             "Classes", "Benign rows used", "Majority baseline (%)", "Best single feature (%)"], rows,
            "Datasets after identifier removal, placeholder normalisation and deduplication, with the single-feature "
            "leakage audit (binary attack-versus-benign accuracy).",
            col_widths=[1.4, 0.8, 0.8, 0.95, 0.8, 0.78, 0.7, 0.8, 0.8, 1.17], label="data",
            notes="Unique rows: rows left after removing exact duplicates and all records whose feature vector occurs "
                  "with more than one label. CICIoT2023 rows used are capped at 40,000 per family, the benign family included.")

    m.heading("4.2 Federated detection experiments", 2)
    m.para("The federated experiments use TON_IoT and CICIoT2023; Edge-IIoTset is excluded for the reasons given in "
           "Section 5.1. Twelve clients, one per edge node, train a multi-layer perceptron with two hidden layers (64 and 32 ReLU "
           "units) and a softmax output over the traffic classes (benign and each attack type). The training data are divided among the clients "
           "either at random (IID) or according to a Dirichlet distribution over classes with $\\alpha$ = 1.0 "
           "(moderately non-IID) or $\\alpha$ = 0.1 (strongly non-IID) [@hsu2019noniid], and every client receives at "
           "least 40 samples. In each of the 40 rounds, every client starts from the current global model and runs 20 "
           "local SGD steps (batch size 128, learning rate 0.05, momentum 0.9, weight decay $10^{-4}$). We compare "
           "FedAvg [@mcmahan2017fedavg], FedProx with $\\mu$ = 0.01 [@li2020fedprox], Krum and Multi-Krum "
           "[@blanchard2017krum], the coordinate-wise median and the coordinate-wise trimmed mean [@yin2018median], "
           "and the trust-aware rule of Eq. {eq:ta}. Krum, Multi-Krum and the trimmed mean all use the same assumed "
           "number of Byzantine clients (three), and the trimmed mean discards three values on each side. A "
           "centralised model trained on the pooled data with the same number of gradient steps serves as a "
           "reference. We tuned only two hyperparameters, on the validation split and with seeds that are not used in "
           "the reported runs: the learning rate (tuned for FedAvg and then used for all rules) and the reliability "
           "cut-off of the trust-aware rule. FedProx's $\\mu$ and the Byzantine bound were fixed a priori.")
    m.para("The poisoning experiments use $\\alpha$ = 1.0 with one, two or three malicious clients (8%, 17% and 25% of "
           "the federation). In targeted label flipping, the malicious clients relabel all of their attack flows as "
           "benign, which teaches the global model to miss attacks. In model poisoning, a malicious client sends its "
           "update multiplied by $-4$ [@fang2020localpoison]. An additional set of runs repeats both attacks with two "
           "malicious clients under $\\alpha$ = 0.1, and a last set uses three malicious clients while Krum, Multi-Krum "
           "and the trimmed mean assume only one. Each configuration is run with 10 seeds, giving "
           f"{S['n_fl_runs']:,} training runs in total. "
           "We report multi-class macro-F1, the area under the ROC curve (AUC) of the attack log-odds "
           "$\\log P(\\mathrm{attack})-\\log P(\\mathrm{benign})$, the false-positive rate (FPR) on benign flows and "
           "the attack detection rate. A run that diverges numerically is scored as detecting nothing, and its FPR is "
           "excluded from the FPR average.")

    m.heading("4.3 City-scale scenarios and policies", 2)
    m.label_next("tab", "policies")
    m.para("The city described in Section 3.1 is simulated with a decision interval of 10 s, and each episode covers "
           "one hour. Within each edge cluster, devices are connected by a small-world contact graph (six neighbours "
           "per device, rewiring probability 0.1) [@watts1998smallworld]. Gateway links join random devices in "
           "different clusters of the same domain (at most 2% of the domain's device count), and each cluster has three "
           "cross-domain links for shared services. "
           "Attacks start after 10 min. In the worm scenario, three compromised devices in one cluster act as seeds, "
           "and the worm spreads with a per-contact probability of 0.03 per step. Flooding uses 30 compromised devices "
           "in two clusters; credential misuse uses 8 compromised healthcare and energy devices that hold valid "
           "credentials and act in 15% of the steps; data injection uses 15 energy devices; and the "
           "impostor scenario places 12 entities with forged classical credentials across all slices. Benign-only "
           "episodes measure false blocking in the absence of any attack. For a given seed, all policies run on the "
           "same environment draws (common random numbers), so differences between policies do not come from "
           "different random draws.")
    m.para("In each step, a device that is not quarantined or blocked emits a benign flow with probability 0.5; a "
           "compromised device that carries out its attack in that step emits an attack flow instead. The threat score of every flow is drawn from the scores that a trained detector "
           "produced on held-out TON_IoT flows of the matching class, so these scores are measured, not modelled. The "
           "detectors come from a 12-client federation in which every edge node holds benign traffic and the attack "
           "classes are distributed with $\\alpha$ = 0.1, so that edge nodes see different attack mixes; five such "
           "federations were trained independently. Global detectors were trained with FedAvg or with the trust-aware "
           "rule, whereas each local detector was trained by one edge node on its own data only. Each detector is "
           "calibrated separately for every edge node on benign commissioning traffic: its attack log-odds are mapped "
           "to a tail score that is zero for 95% of the benign reference flows. In this mapping, ties receive their "
           "mid-rank, so a score shared by many benign flows carries no evidence. The reference flows, the flows used "
           "to calibrate operating points and the flows used in the reported runs are three disjoint subsets of the "
           "held-out data. The behavioural profile is the only modelled evidence input: a per-device traffic statistic whose "
           "mean shifts when the device attacks. Only the trust-based policies use it, and one ablation removes it. "
           "Table {tab:policies} lists the policies.")
    L = POL_LAB
    rows = [
        [L["none"], "–", "–", "–", "–", "Reference for containment"],
        [L["static_zta"], "Local", "Rule: score above threshold in 3 consecutive observations", "No", "None",
         "Conventional zero trust"],
        [L["fl_ids"], "Global (FedAvg)", "Rule: 2 consecutive observations", "No", "None",
         "Federated detection alone"],
        [L["zta_fixedpqc"], "Local", "Rule: 3 consecutive observations", "No", "All sessions",
         "Fixed quantum-safe authentication"],
        [L["dt_ids_nofl"], "Local", "Rule: 2 consecutive observations", "Yes", "None",
         "Twin without federation"],
        [L["apqzto"], "Global (trust-aware)", "Trust score with zero-trust veto, Eq. {eq:trust}", "Yes", "Adaptive",
         "Full framework"],
        [L["apqzto_nopqc"], "Global (trust-aware)", "Trust score, Eq. {eq:trust}", "Yes", "None", "Ablation"],
        [L["apqzto_nodt"], "Global (trust-aware)", "Trust score, Eq. {eq:trust}; a static rule isolates a cluster "
         "once three of its devices are suspected", "No", "Adaptive", "Ablation"],
        [L["apqzto_nofl"], "Local", "Trust score, Eq. {eq:trust}", "Yes", "Adaptive", "Ablation"],
        [L["apqzto_notrust"], "Global (trust-aware)", "Rule: 2 consecutive observations", "Yes",
         "Adaptive", "Ablation"],
        [L["apqzto_nobeh"], "Global (trust-aware)", "Trust score without the behavioural term ($B_{i}$ = 1; "
         "$H_{i}$ updated from $F_{i}$ only)", "Yes", "Adaptive", "Ablation of the modelled input"],
        [L["apqzto_noveto"], "Global (trust-aware)", "Additive score of Eq. {eq:trust} without the veto", "Yes",
         "Adaptive", "Ablation (design variant)"],
        [L["apqzto_twinrisk"], "Global (trust-aware)", "Additive score minus 0.40 $D_{i}$ of Eq. {eq:twinrisk}; "
         "no veto", "Yes", "Adaptive", "Ablation (original A-PQZTO design)"],
    ]
    m.table(["Policy", "Detector", "Decision logic", "Digital twin", "PQC sessions", "Purpose"], rows,
            "Policies compared in the city-scale experiments.", col_widths=[1.7, 1.25, 1.75, 0.6, 0.8, 1.2],
            label="policies", align=["left"] * 6,
            notes="Rule-based policies quarantine a device after the stated number of consecutive observations whose "
                  "smoothed detector score exceeds $0.5-\\theta$. Suspected: trust below $\\tau_{restrict,d}$, or, for "
                  "rule-based policies, a score above that threshold. Wherever a digital twin is used, it validates "
                  "cluster isolation with Eq. {eq:twinrule}.")

    m.heading("4.4 Operating-point calibration, metrics and design selection", 2)
    m.para("Comparing policies at different alarm levels would favour whichever policy acts most often, and counting "
           "only quarantine and blocking would let a policy hide its cost in cluster isolation or rate limiting. We "
           "therefore calibrated the threshold offset $\\theta$ of every policy on benign validation episodes (seeds "
           "101–104 and the validation evidence pool, none of which is used for testing) under a joint budget. Two "
           "quantities must both stay at or below 0.5%: the share of benign device-steps spent quarantined or blocked, "
           "and the criticality-weighted service disruption defined below, expressed as a share of the city's "
           "weighted capacity $\\sum_{i}s_{d}c_{i}$. The largest feasible $\\theta$ was selected on a grid from "
           "$-0.45$ to $0.30$ in steps of 0.05 and then refined in steps of 0.01. A larger $\\theta$ makes every "
           "policy respond earlier: it raises the action thresholds of Eq. {eq:thresh} for the trust-based policies "
           "and lowers the detection threshold $0.5-\\theta$ of the rule-based ones. The same $\\theta$ is used in "
           "every scenario. In the worm scenario, containment efficiency compares the number of devices ever "
           "compromised with the corresponding number in the no-response run of the same seed:")
    m.equation("CE=1-\\frac{|\\mathcal{A}_{policy}|}{|\\mathcal{A}_{none}|}", label="ce")
    m.para("For the non-spreading scenarios, we use the attack-success ratio, defined as the number of attack-active "
           "device-steps that were not stopped divided by the same number without any response (for impostors, the "
           "number of steps in which an impostor had access is counted instead):")
    m.equation("ASR=\\frac{\\sum_{t}|\\mathrm{active}_{policy}(t)|}{\\sum_{t}|\\mathrm{active}_{none}(t)|}", label="asr")
    m.para("Service disruption weights each benign device-step by $s_{d}c_{i}$ times a factor for the strongest "
           "restriction that the device experiences (1 for quarantine or blocking, 0.5 inside an isolated cluster, 0.2 "
           "when rate-limited); it is reported in weighted device-hours per hour. For the worm, we also report the "
           "share of runs in which every compromised device was eventually removed and the time this took, and for "
           "test seeds 21–30 we recorded the number of compromised devices at every step. For "
           "post-quantum protection, we count handshakes and report the share of sessions whose keys were "
           "established only classically,")
    m.equation("E_{HNDL}=\\frac{N_{cl}}{N_{sess}}", label="hndl")
    m.para("where $N_{sess}$ is the number of sessions established in the episode and $N_{cl}$ the number of those "
           "without post-quantum key establishment. We compute it both over all sessions and over the sessions of the "
           "sensitive slices. Because the session policy "
           "determines which sessions use post-quantum keys, $E_{HNDL}$ is an accounting property of each design rather "
           "than an experimental outcome, and we report it alongside the cost at which it is obtained. We also report "
           "the decision time per step, measured on the evaluation host.")
    _design_selection(m)

    m.heading("4.5 Twin fidelity, stress test and scalability", 2)
    m.para("Three further experiments reuse the test seeds and the calibrated operating points. In the twin-fidelity "
           "test (worm scenario, A-PQZTO), the twin's copy of the contact graph misses 0, 10, 30 or 50% of the true "
           "links, which are replaced by as many spurious links within the same domain, and its prior $\\hat{\\beta}$ "
           "is 0.015, 0.03 or 0.06 against a true rate of 0.03; $h$ = 12, $M$ = 8 and the rule of Eq. {eq:twinrule} "
           "are unchanged. The stress test uses a worm that is identical to the worm scenario except for its "
           "per-contact propagation probability of 0.10, about three times the twin's prior of 0.03. It compares no response, Static ZTA, FL-only IDS, DT-assisted "
           "IDS w/o FL, A-PQZTO, A-PQZTO w/o twin, A-PQZTO w/o adaptive trust and A-PQZTO w/o zero-trust veto, and "
           "repeats the twin sweep for A-PQZTO with $\\hat{\\beta}$ = 0.015, 0.03, 0.06 or 0.10. The scalability "
           "test runs A-PQZTO, A-PQZTO w/o twin and FL-only IDS on the worm scenario in cities of one, two, four and "
           "eight times the reference size (1,500 to 12,000 devices, still served by 12 edge nodes), with seeds 21–23 "
           "on a single worker so that parallel runs cannot distort the timing.")

    m.heading("4.6 Post-quantum measurements", 2)
    m.para("All post-quantum measurements used OpenSSL 3.5.6, which implements ML-KEM (FIPS 203) and ML-DSA "
           "(FIPS 204) natively. Primitive throughput was measured with the openssl speed command on an otherwise idle "
           "host, covering all KEM and signature algorithms (five repetitions of 3 s for KEMs and three of 2 s for "
           "signatures). Complete TLS 1.3 handshakes were run over the loopback interface between the OpenSSL "
           "s_server and s_client tools in two configurations: a classical one (X25519 key exchange with an ECDSA "
           "P-256 certificate) and a hybrid post-quantum one (X25519MLKEM768 [@rfc10024] with an ML-DSA-65 "
           "certificate). Handshake sizes were taken from the message trace, and full-handshake rates from s_time "
           "(three runs of 8 s each). These are host-level measurements. Rather than assume timings for constrained "
           "devices, we report the slowdown factor $\\kappa$ up to which a handshake still fits each slice budget "
           "$L_{d}$.")
    try:
        q_meas = f" ({S['pqc']['tls']['hybrid']['client_cpu_ms']:.1f} ms)"
    except (KeyError, TypeError):
        q_meas = ""
    txt = ("The city simulation needs a single value: it assumes $Q$ = 2.0 ms and $\\kappa$ = 1, close to the client "
           f"CPU time of one hybrid handshake measured here{q_meas}, so every re-authentication fits its slice budget.")
    if os.path.exists(PQCOST):
        txt += (" A sensitivity run repeats the impostor, credential-misuse and benign scenarios for A-PQZTO on the "
                "test seeds with $\\kappa$ = 1, 3, 10, 30 and 60 (handshakes of 2 to 120 ms), so that re-authentication "
                "is deferred in every slice whose budget the handshake exceeds.")
    m.para(txt)

    m.heading("4.7 Implementation and statistical analysis", 2)
    m.para("All experiments ran on a single laptop (Intel Core i7-4810MQ at 2.8 GHz, 8 logical cores, 12 GB RAM, "
           "Windows 10) with Python 3.14.0, PyTorch 2.14.1 (CPU), scikit-learn 1.8.0, NumPy 2.3.5, SciPy 1.16.3, "
           "pandas 2.3.3 and NetworkX 3.6.1; no GPU was used. Means are reported with 95% bootstrap confidence "
           "intervals (5,000 resamples over seeds) [@efron1993bootstrap]. Paired comparisons over seeds use the "
           "two-sided Wilcoxon signed-rank test [@wilcoxon1945] with Benjamini–Hochberg correction [@benjamini1995fdr] "
           "within each experiment family (federated, city-scale and stress tests), and Cliff's $\\delta$ as the effect "
           "size. Each run is stored "
           "as one line in a results file, and scripts generate all figures and tables from these files.")
